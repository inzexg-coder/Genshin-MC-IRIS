package net.teyvat.combat;

/**
 * Комбо атак путешественника (Итэр/Люмин) с обычным мечом, как в Genshin:
 * серия из 5 ударов, у каждого своя длительность, момент нанесения урона
 * и множитель урона от атаки. Общие данные для клиента (тайминги анимации)
 * и сервера (множители урона).
 *
 * Удары (анимации — scripts/port_bc_combo.py из готовых клипов BetterCombat):
 *   1. горизонтальный удар слева направо;
 *   2. длинный апперкот справа снизу вверх влево;
 *   3. разворот через левое плечо на 360° с рубящим ударом по диагонали
 *      (полный оборот делает root модели — всё тело и клинок поворачиваются
 *      вместе, без отдельного вращения корпуса);
 *   4. горизонтальный удар справа налево;
 *   5. широкий замах, удар справа налево и увод клинка за спину.
 *
 * Анимации — scripts/gen_combo.py: направления клинка считаются солвером
 * под реальную игровую геометрию (scripts/blade_geo.py), поэтому разрез
 * совпадает с мечом. Комбо идёт по КЛИКАМ: удержание ЛКМ не цепляет
 * следующий удар; пока с последнего клика не прошло ~1 с (RESET_TICKS),
 * серия продолжается со следующего удара — пауза дольше сбрасывает комбо.
 * После 5-го удара — пауза FINAL_COOLDOWN_TICKS (~1 сек): клики глотаются,
 * новое комбо стартует только с первого удара. Каждый удар МГНОВЕННЫЙ:
 * замах сжат в первые ~10% клипа (быстрый размах), урон наносится уже
 * на 1-2 тике, остаток клипа — широкое сопровождение и возврат в стойку.
 *
 * Заряженная атака (CHARGE_INDEX = 5, в комбо не входит): тап — мгновенный
 * удар комбо; если ЛКМ не отпускать, после удара начинается накопление
 * (FULL_CHARGE_TICKS = 2 сек). Отпускание в любой момент — спин на 360°
 * с хитом по полному кругу вокруг героя («орбиты атомов»), урон зависит
 * от уровня заряда (CHARGE_MIN_MULT..1.0); не отпускать — через 3 сек
 * автозапуск максимальной. Тратит стамину, после неё серия сбрасывается.
 */
public final class SwordCombo {
    /** Число ударов в комбо (у путешественника с мечом — 5). */
    public static final int HIT_COUNT = 5;
    /** Индекс заряженного удара (6-я анимация, НЕ входит в комбо): спин-атака
     *  по кругу вокруг героя, как в Genshin у путешественника — хит по всей
     *  площади вокруг тела («орбиты атомов»). */
    public static final int CHARGE_INDEX = HIT_COUNT;
    /** Длительность каждого удара в тиках (полный круг ≈ 3.5 сек): удар
     *  МГНОВЕННЫЙ — t=0 клипа это уже финал предыдущего удара (seam),
     *  замах сжат в первые ~10% клипа (очень быстрый размах, пик
     *  скорости ~0.12), там и наносится урон; остаток клипа — широкое
     *  сопровождение клинка и мягкий возврат. Удары максимально широкие
     *  (клинок уводится далеко в замах и сопровождение), корпус наклоняется
     *  в удар малыми углами (root.pitch) с выпадом ног, левая рука —
     *  естественный противовес (см. gen_combo.py). */
    public static final int[] DURATION_TICKS = {10, 12, 18, 12, 20, 26};
    /** Тик удара, в который наносится урон: пик скорости клинка в свинге
     *  (замах сжат в первые ~10% клипа, см. scripts/gen_combo.py):
     *  удар 1 — пролёт слева направо, удар 2 — апперкот снизу вверх,
     *  удар 3 — разворот (пик угловой скорости root), удар 4 — пролёт
     *  справа налево, удар 5 — широкий низкий свинг с прокатом. */
    public static final int[] DAMAGE_TICKS = {1, 1, 2, 1, 2, 2};
    /** Множители урона от атаки: 44.5% / 43.4% / 53.0% / 58.3% / 70.8% (Aether, Lv1). Заряженная: 55.9+60.7=116.6%. */
    public static final float[] MULTIPLIERS = {0.445f, 0.434f, 0.530f, 0.583f, 0.708f, 1.166f};
    /** Окно комбо от последнего клика: пока прошло ≤ RESET_TICKS (~1 сек),
     *  серия продолжается со следующего удара; пауза дольше — сбрасывается. */
    public static final int RESET_TICKS = 20;
    /** Пауза после пятого (финального) удара: ~1 сек, в течение которой
     *  клики ЛКМ глотаются — нельзя сразу начать новое комбо. */
    public static final int FINAL_COOLDOWN_TICKS = 8;
    /** Полный заряд заряженной атаки: 3 секунды (60 тиков). Если отпустить
     *  раньше — урон меньше (уровень заряда), не отпускать — автозапуск
     *  максимальной. */
    public static final int FULL_CHARGE_TICKS = 40;
    /** Минимальная доля урона заряженной атаки при раннем отпуске (уровень
     *  заряда 0): спин бьёт вполсилы; на полном заряде — полный множитель. */
    public static final float CHARGE_MIN_MULT = 0.5f;
    /** Микро-рывок героя вперёд на момент удара (блоки/тик): каждый удар
     *  проталкивает героя по направлению атаки, как в Genshin. Клавиши
     *  движения во время удара заблокированы — двигает только рывок.
     *  Пятый удар — мощный прокат вперёд. */
    public static final float[] LUNGE_STRENGTH = {0.2f, 0.22f, 0.3f, 0.22f, 0.72f, 0.4f};
    /** Вертикальный подброс на ударе (пятый удар — низкий прокат, без прыжка). */
    public static final float[] LUNGE_UP = {0f, 0f, 0f, 0f, 0f, 0f};
    /** Отбрасывание цели по ударам (сервер): финальные удары бьют сильнее. */
    public static final float[] KNOCKBACK = {0.15f, 0.14f, 0.22f, 0.18f, 0.65f, 1.0f};

    /** Дальность меча по ударам (сервер, хитбоксы): 5-й — глубокий прокат,
     *  3-й — широкий разворот, 2-й — высокий апперкот, заряженный — полный
     *  круг вокруг героя, максимальный по объёму (почти сфера). */
    public static final float[] HIT_REACH = {4.0f, 4.2f, 4.4f, 4.0f, 5.0f, 7.0f};
    /** Полуширина коробки поиска целей по ударам. */
    public static final float[] HIT_HALF_WIDTH = {1.6f, 1.4f, 2.8f, 1.6f, 2.4f, 6.0f};
    /** Минимальный косинус угла взгляд-цель: 3-й — полный круг вокруг (-1),
     *  5-й — широкий веер, заряженный спин — тоже полный круг вокруг (-1),
     *  остальные — обычный размах. */
    public static final float[] HIT_FRONT_DOT = {0.45f, 0.45f, -1.0f, 0.45f, 0.35f, -1.0f};
    /** Максимальное боковое отклонение цели от луча взгляда (не для круга). */
    public static final float[] HIT_MAX_LATERAL = {1.4f, 1.2f, 3.2f, 1.4f, 2.2f, 6.0f};
    /** Верх коробки поиска над глазами игрока (апперкот 2-го бьёт высоко). */
    public static final float[] HIT_BOX_TOP = {1.2f, 2.4f, 1.6f, 1.2f, 1.6f, 2.6f};
    /** Низ коробки под глазами (5-й — низкий свинг). */
    public static final float[] HIT_BOX_BOTTOM = {-1.2f, -1.0f, -1.2f, -1.2f, -1.6f, -2.2f};

    /** Тики хит-стопа (hitlag) при ПОПАДАНИИ: анимация героя и цели замирает
     *  на пару кадров — вес удара, как в Genshin. Промах хит-стопа не даёт. */
    public static final int[] HITLAG_TICKS = {3, 3, 4, 3, 6, 7};

    /** Poise Damage: сколько стойкости снимает каждый удар (из Genshin wiki).
     *  При 0 стойкости — оглушение моба (длинный хит-стоп + усиленный кнокбек). */
    public static final float[] POISE_DAMAGE = {41.4f, 43.2f, 53.1f, 57.6f, 70.2f, 50.6f};

    /** Уровень оглушения (Stagger Level): 0=Light, 1=Heavy, 2=Air (подбрасывает).
     *  Удары 1-4 = Heavy, 5-й = Air (отбрасывает вверх), заряженная = Air. */
    public static final int[] STAGGER_LEVEL = {1, 1, 1, 1, 2, 2};

    /** Доля LUNGE_STRENGTH, отдаваемая «шагу вперёд» в начале удара
     *  (остальное — толчок на тике урона): серия продвигает героя
     *  с каждым ударом, как в Genshin. */
    public static final float START_STEP_FACTOR = 0.4f;

    private SwordCombo() {}

    /** Прогресс удара 0..1 (для интерполяции поз). */
    public static float progress(int hitTicks, int hitIndex) {
        return Math.max(0f, Math.min(1f, (float) hitTicks / DURATION_TICKS[hitIndex]));
    }
}
